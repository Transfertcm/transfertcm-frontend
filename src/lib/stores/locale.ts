// ── Dictionnaires consolidés ───────────────────────────────────────────────────

const dictionaries: Record<LocaleCode, Record<string, string>> = { fr, en, it, es, pt }

// ── Store de locale ────────────────────────────────────────────────────────────

function createLocaleStore() {
  const STORAGE_KEY = 'tcm_locale'

  const initial: LocaleCode = (() => {
    if (typeof localStorage === 'undefined') return 'fr'
    const saved = localStorage.getItem(STORAGE_KEY) as LocaleCode | null
    return saved && saved in dictionaries ? saved : 'fr'
  })()

  const store = writable<LocaleCode>(initial)

  store.subscribe((code) => {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY, code)
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = code
    }
  })

  return store
}

export const locale = createLocaleStore()

// ── Fonction de traduction (store dérivé) ─────────────────────────────────────
//
// En template Svelte : {$t('clé')} ou {$t('clé', { var: val })}
// En script section  : translate('clé') ou translate('clé', { var: val })

type TranslateFn = (key: string, vars?: Record<string, string | number>) => string

export const t = derived<typeof locale, TranslateFn>(locale, ($locale) => {
  const dict = dictionaries[$locale] ?? fr
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = dict[key] ?? key
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, String(v))
      }
    }
    return text
  }
})

// ── Fonction non-réactive (usage dans les sections <script>) ──────────────────
//
// Utilise la valeur courante du store — ne se met pas à jour automatiquement.
// Utiliser $t dans les templates à la place.

export function translate(key: string, vars?: Record<string, string | number>): string {
  return get(t)(key, vars)
}

// ── Helper pour changer de langue ─────────────────────────────────────────────

export function setLocale(code: LocaleCode): void {
  locale.set(code)
}
